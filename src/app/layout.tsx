import type { Metadata } from "next";
import { Plus_Jakarta_Sans } from "next/font/google";
import "./globals.css";
import { cookies } from "next/headers";

const jakarta = Plus_Jakarta_Sans({
  subsets: ["latin"], display: "swap"
})

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const theme = (await cookies()).get("theme")?.value // checks the theme cookie (fixing issue with saved dark mode having a flicker of white before correcting)



  return (
    <html
      lang="en"
      className={`${jakarta.className} font-sans h-full antialiased ${theme == "dark" ? "dark" : ""}`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
